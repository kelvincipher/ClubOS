import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import {database} from '../src/store.js';
import {createApp} from '../src/app.js';
if(!process.env.FIRESTORE_EMULATOR_HOST)throw Error('Tests require the emulator, never a real database.');
process.env.FIREBASE_PROJECT_ID='demo-clubos';
const db=database(),app=createApp(db,'test-only-secret-that-is-longer-than-32-characters');
after(()=>db.terminate());
const call=(token,method,path,body)=>request(app)[method]('/api/'+path).set('Authorization','Bearer '+token).send(body);
async function account(name){const email=`${name}-${Date.now()}-${Math.random()}@example.com`,r=await request(app).post('/api/auth/register').send({name,email,password:'Test-password-123!'});assert.equal(r.status,201,JSON.stringify(r.body));return {...r.body,email};}
test('complete lifecycle, cross-club permissions, capacity, duplicate check-in and handover',async()=>{
 const president=await account('president'),student=await account('student'),outsider=await account('outsider'),p=president.token,s=student.token,o=outsider.token;
 let r=await call(p,'post','clubs',{name:'Test Society',description:'A club for integration testing.',category:'Technology'});assert.equal(r.status,201);const cid=r.body.id;
 const campaignBody={title:'New recruits',deadline:new Date(Date.now()+86400000).toISOString()};
 assert.equal((await call(s,'post',`clubs/${cid}/campaigns`,campaignBody)).status,403);
 assert.equal((await call(p,'post',`clubs/${cid}/campaigns`,campaignBody)).status,201);
 let state=(await call(p,'get',`clubs/${cid}`)).body;const campaign=state.campaigns[0].id;
 assert.equal((await call(s,'post',`campaigns/${campaign}/apply`,{motivation:'I want to help organize useful activities.'})).status,201);
 assert.equal((await call(s,'post',`campaigns/${campaign}/apply`,{motivation:'A repeated application should be blocked.'})).status,409);
 state=(await call(p,'get',`clubs/${cid}`)).body;const application=state.applications[0].id;
 assert.equal((await call(o,'get',`clubs/${cid}`)).body.applications.length,0);
 assert.equal((await call(o,'patch',`applications/${application}`,{status:'accepted'})).status,403);
 assert.equal((await call(p,'patch',`applications/${application}`,{status:'interview'})).status,200);
 assert.equal((await call(p,'patch',`applications/${application}`,{status:'accepted'})).status,200);
 assert.equal((await call(p,'patch',`applications/${application}`,{status:'rejected'})).status,400);
 assert.equal((await call(s,'get',`clubs/${cid}`)).body.membership.role,'member');
 assert.equal((await call(p,'post',`clubs/${cid}/events`,{title:'Launch',description:'An event for new members.',location:'Room 1',starts_at:new Date(Date.now()+86400000).toISOString(),capacity:1})).status,201);
 state=(await call(p,'get',`clubs/${cid}`)).body;const event=state.events[0].id;
 assert.equal((await call(o,'post',`events/${event}/register`,{})).status,403);
 assert.equal((await call(s,'post',`events/${event}/register`,{})).status,201);
 assert.equal((await call(s,'post',`events/${event}/register`,{})).status,409);
 assert.equal((await call(p,'post',`events/${event}/register`,{})).status,400);
 const token=(await call(s,'get',`clubs/${cid}`)).body.registrations[0].token;
 assert.equal((await call(s,'post','checkin',{token})).status,403);
 const checks=await Promise.all([call(p,'post','checkin',{token}),call(p,'post','checkin',{token})]);assert.deepEqual(checks.map(r=>r.status).sort(),[200,409]);
 assert.equal((await call(p,'post',`clubs/${cid}/resources`,{title:'Handbook',url:'javascript:alert(1)'})).status,400);
 assert.equal((await call(p,'post',`clubs/${cid}/resources`,{title:'Handbook',url:'https://example.com/handbook'})).status,201);
 assert.equal((await call(p,'post',`clubs/${cid}/tasks`,{title:'Prepare handover'})).status,201);
 state=(await call(p,'get',`clubs/${cid}`)).body;
 assert.equal((await call(s,'patch',`tasks/${state.tasks[0].id}`,{done:true})).status,403);
 assert.equal((await call(p,'patch',`tasks/${state.tasks[0].id}`,{done:true})).status,200);
 assert.equal((await call(s,'post',`clubs/${cid}/handover`,{to_id:president.user.id,note:'This must be rejected.'})).status,403);
 assert.equal((await call(p,'post',`clubs/${cid}/handover`,{to_id:student.user.id,note:'Here are the notes for our next team.'})).status,200);
 assert.equal((await call(s,'get',`clubs/${cid}`)).body.membership.role,'president');
 state=(await call(p,'get',`clubs/${cid}`)).body;assert.equal(state.membership.role,'officer');assert.equal(state.handovers.length,1);assert.equal(state.resources.length,1);
 assert.equal((await call(p,'post',`clubs/${cid}/handover`,{to_id:outsider.user.id,note:'Old president cannot transfer again.'})).status,403);
 assert.equal((await request(app).post('/api/auth/login').send({email:student.email,password:'Test-password-123!'})).status,200);
 assert.equal((await request(app).get('/api/clubs')).status,401);
});
